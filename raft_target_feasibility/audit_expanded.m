function audit_expanded
    root=fileparts(mfilename('fullpath'));
    addpath(fullfile(root,'core'));
    maxNumCompThreads(1);
    od=fullfile(root,'outputs');
    files=dir(fullfile(od,'*_op*_seed*.mat'));
    rows={};
    trajectories={};
    for j=1:numel(files)
        s=load(fullfile(od,files(j).name));
        r=s.run;
        c=r.c;
        K=numel(r.edges)-1;
        N=K+1;
        D=2*N;
        for k=1:1
            cp=r.checkpoints{k};
            [x,~,flag]=quadprog(eye(D),-cp.x,r.A,r.b,r.E,r.eq,zeros(D,1),ones(D,1),[],optimoptions('quadprog','Display','off'));
            assert(flag>0);
            amount=reshape(x,N,2).'.*r.total;
            cc=c;
            cc.n0=amount(:,1);
            cc.dose=r.total-cc.n0;
            rates=amount(:,2:end)./diff(r.edges);
            cc.feed_edges=r.edges;
            cc.feed_time=r.edges(end);
            cc.RelTol=5e-10;
            cc.AbsTol=2e-14;
            cc.max_step=15;
            cc.output_dt=2.5;
            o=resolution_simulate(cc,rates);
            grid=linspace(1e-4,.8,10001);
            [u,ix]=unique(o.Xmol);
            f=interp1(u,o.Finstant(ix),grid);
            err=f-target_curve(grid,cc);
            rmse=sqrt(trapz(grid,err.^2)/(.8-1e-4));
            [peak,ip]=max(abs(err));
            vm=cc.p.MW./(1000*cc.p.rho_monomer_g_mL);
            q=rates.*vm*1000;
            linear=max([0;r.A*x-r.b;abs(r.E*x-r.eq)]);
            doseError=max(abs(cc.n0+rates*diff(r.edges).'-r.total));
            checks=max([o.checks.component,o.checks.raft,o.checks.units,o.checks.chains]);
            process=o.Xmol(end)>=.8&&o.Xmass(end)>=.8&&max(o.V)<=1.05&&max(q,[],'all')<=.18+1e-8&&max(sum(q,1))<=.25+1e-8&&linear<1e-8&&doseError<1e-8;
            passed=process&&rmse<=.02&&peak<=.05;
            row=struct('target',r.id,'expanded',r.expanded,'seed',r.seed,'budget',cp.budget,...
            'RMSE_percent',rmse*100,'max_error_percent',peak*100,'peak_progress',grid(ip),...
            'start_error_percent',abs(err(1))*100,'end_error_percent',abs(err(end))*100,...
            'Xmol_percent',o.Xmol(end)*100,'Xmass_percent',o.Xmass(end)*100,'max_volume_L',max(o.V),...
            'max_single_pump_mL_s',max(q,[],'all'),'max_total_pump_mL_s',max(sum(q,1)),...
            'initial_St_fraction',cc.n0(1)/sum(cc.n0),'dose_error_mol',doseError,'conservation',checks,...
            'projection_distance',norm(x-cp.x),'process_feasible',process,'target_met',passed,...
            'search_seconds',cp.elapsed,'actual_total_calls',r.calls,'actual_total_odes',r.odes,'error_count',numel(r.errors));
            rows{end+1}=row;
            trajectories{end+1}=struct('metrics',row,'grid',grid,'f',f,'target',target_curve(grid,cc),'rates',rates,'edges',r.edges,'n0',cc.n0);
            fprintf('AUDIT %s op%d seed%d B%d RMSE%.5f peak%.5f pass%d\n',r.id,r.expanded,r.seed,cp.budget,rmse*100,peak*100,passed);
        end
    end
    T=struct2table(vertcat(rows{:}));
    writetable(T,fullfile(od,'expanded_verified.csv'));
    save(fullfile(od,'expanded_trajectories.mat'),'T','trajectories','-v7');
end
